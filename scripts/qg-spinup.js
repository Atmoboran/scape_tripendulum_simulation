// Spins the two-layer model up from small seeded noise into equilibrated
// eddy turbulence (about 250 days) and writes three snapshots, 120 model
// days apart, to
// data/qg-start.js (Float32, base64). The app starts from these, so a
// visitor never waits through years of spin-up. Reproducible: same seed,
// same file.   Run:  node scripts/qg-spinup.js
const fs = require('fs');
const path = require('path');
const QG = require('../js/models/qg2layer.js');
const { rng } = require('../js/models/lorenz96.js');

const YEAR = 360 * QG.DAY;
const m = new QG.Model();
const r = rng(20261029);
m.setQ(new Float64Array(m.n).map(() => 1e-9 * (r() - 0.5)), new Float64Array(m.n));

const b64 = (arr) => Buffer.from(new Float32Array(arr).buffer).toString('base64');
const snaps = [];
const times = [2 * YEAR, 2 * YEAR + 120 * QG.DAY, 2 * YEAR + 240 * QG.DAY];
while (snaps.length < times.length) {
  m.step();
  if (m.t >= times[snaps.length]) {
    const [q1, q2] = m.getQ();
    snaps.push({ day: Math.round(m.t / QG.DAY), q1: b64(q1), q2: b64(q2) });
    console.log('snapshot at day', snaps[snaps.length - 1].day);
  }
}
const out = '// Generated by scripts/qg-spinup.js -- equilibrated starts for the\n' +
  '// two-layer model (' + m.nx + '×' + m.ny + ', parameters of QG2.DEFAULTS), potential\n' +
  '// vorticity of both layers as Float32 in base64. Do not edit by hand.\n' +
  'window.QG_START = ' + JSON.stringify({ nx: m.nx, ny: m.ny, snapshots: snaps }) + ';\n';
fs.writeFileSync(path.join(__dirname, '..', 'data', 'qg-start.js'), out);
console.log('wrote data/qg-start.js', (out.length / 1024).toFixed(1) + ' KB');
